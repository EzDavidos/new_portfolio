/* ============================================================
   Течение — WebGL

   Поверхность считается как поле высот: домен-варпинг фрактального
   шума даёт складки, из градиента поля строится нормаль, по нормали
   — затенение и блик. Поэтому это читается как жидкость, а не туман.

   Композиция задана отдельно от материала: осевая линия волны входит низко
   слева, S-образно поднимается через центр и выкатывается гребнем в правой
   трети. Домен изгибается по этой линии, поэтому ленты и снос идут вдоль
   волны, а не по прямой диагонали.

   Четыре особенности:
   · домен растянут вдоль направления волны — волны получаются длинными
   · домен изогнут по осевой линии — форма и течение совпадают по построению
   · разрешение рендера подстраивается под реальный FPS
   · курсор мягко расталкивает поверхность в радиусе ~2 см
   ============================================================ */
(function () {
  'use strict';

  var canvases = document.querySelectorAll('canvas.water');
  if (!canvases.length) return;

  // Радиус линзы под курсором — 1.5 см при 96 dpi. Задан в физических
  // единицах осознанно: полтора сантиметра не должны зависеть от диагонали.
  var PX_PER_CM = 96 / 2.54;
  var RADIUS_CSS_PX = 1.5 * PX_PER_CM;

  var VERT = [
    'attribute vec2 aPos;',
    'void main(){ gl_Position = vec4(aPos, 0.0, 1.0); }'
  ].join('\n');

  var FRAG = [
    'precision highp float;',
    'uniform vec2  uRes;',
    'uniform float uTime;',
    'uniform float uDark;',
    'uniform vec2  uMouse;',
    'uniform float uMouseAmt;',
    'uniform float uRadius;',

    'float hash(vec2 p){',
    '  p = fract(p * vec2(123.34, 456.21));',
    '  p += dot(p, p + 45.32);',
    '  return fract(p.x * p.y);',
    '}',

    // квинтическая интерполяция вместо кубической: убирает решётчатость,
    // которая на пологих градиентах читается как сетка
    'float noise(vec2 p){',
    '  vec2 i = floor(p), f = fract(p);',
    '  vec2 u = f * f * f * (f * (f * 6.0 - 15.0) + 10.0);',
    '  float a = hash(i);',
    '  float b = hash(i + vec2(1.0, 0.0));',
    '  float c = hash(i + vec2(0.0, 1.0));',
    '  float d = hash(i + vec2(1.0, 1.0));',
    '  return mix(mix(a, b, u.x), mix(c, d, u.x), u.y);',
    '}',

    // Спад амплитуды 0.50: средние частоты сохранены — они дают
    // структуру ВНУТРИ крупных лент, без них поверхность выглядит
    // пустым атласом. Крупность формы задают масштаб и вытяжка домена,
    // а не отсечение октав. Сумма амплитуд 0.9375, среднее поля ~0.47.
    'float fbm4(vec2 p){',
    '  float v = 0.0, a = 0.5;',
    '  mat2 m = mat2(1.6, 1.2, -1.2, 1.6);',
    '  for (int i = 0; i < 4; i++){ v += a * noise(p); p = m * p; a *= 0.50; }',
    '  return v;',
    '}',

    // Смещение домена считается ОДИН раз и переиспользуется для всех
    // трёх выборок высоты: оно низкочастотное и на масштабе производной
    // не меняется. Это втрое дешевле полного пересчёта поля.
    //
    // Сила варпа полная — именно он создаёт крупную структуру и контраст.
    // Хаос давал не он, а время, входившее сюда с противоположными
    // знаками: поле кипело на месте. Теперь время здесь одно и очень
    // медленное, а двигает картину единый снос в main().
    //
    // Знак минус: выборка F(x + D) сдвигает узор в сторону -D, поэтому
    // вычитание времени гонит внутренний варп ВПЕРЁД по домену — туда же,
    // куда сносится сама масса. Иначе материал течёт в одну сторону,
    // а его внутренняя структура переливается в другую.
    'vec2 warpOffset(vec2 p, float t){',
    '  vec2 q = vec2(fbm4(p), fbm4(p + vec2(4.2, 1.3)));',
    '  vec2 r = vec2(fbm4(p + 2.1 * q + vec2(1.7, 9.2) - t * 0.06),',
    '                fbm4(p + 2.1 * q + vec2(8.3, 2.8) - t * 0.05));',
    '  return 2.0 * r;',
    '}',

    // Пузырьки. Домен режется на ячейки; часть из них по хешу получает пузырь
    // со своим радиусом и положением внутри ячейки. Радиус держится меньше
    // половины ячейки, поэтому соседей проверять не нужно — один хеш вместо
    // девяти. Рисуется не диск, а кольцо: у пузыря в воде видна кромка, тело
    // остаётся прозрачным.
    'vec3 bubble(vec2 q, float sd){',
    '  vec2 c = floor(q);',
    '  float h1 = hash(c + sd);',
    '  float h2 = hash(c + sd + 7.31);',
    '  float h3 = hash(c + sd + 13.7);',
    // Занята примерно каждая восьмая ячейка. При каждой третьей решётка
    // читалась насквозь и пузыри выглядели узором, а не пузырями.
    '  float on = step(0.87, h1);',
    '  vec2  ctr = vec2(0.5) + (vec2(h2, h3) - 0.5) * 0.62;',
    // Разброс радиуса вчетверо, а не вдвое: одинаковый размер — вторая примета
    // решётки после одинакового шага.
    '  float rad = (0.045 + 0.150 * h2 * h2) * on;',
    '  vec2  d2 = fract(q) - ctr;',
    '  float d = length(d2);',
    '  float body = 1.0 - smoothstep(rad * 0.55, rad * 0.98, d);',
    '  float rim  = smoothstep(rad * 0.55, rad * 0.90, d) * (1.0 - smoothstep(rad * 0.90, rad * 1.10, d));',
    // Знак стороны кольца относительно света: снизу-слева кромка тёмная,
    // сверху-справа — светлая. Без этого пузырь читается плоским значком.
    '  float lit = d > 0.0001 ? dot(d2 / d, vec2(-0.55, 0.84)) : 0.0;',
    '  return vec3(body, rim, lit);',
    '}',

    'void main(){',
    '  vec2 uv = gl_FragCoord.xy / uRes;',
    '  float asp = uRes.x / uRes.y;',
    '  float t = uTime * 0.15;',

    /* ---------- композиция: осевая линия волны ---------- */
    // Волна входит низко слева, S-образно поднимается через центр и
    // выкатывается высоким гребнем в правой трети. uv.y здесь — экранный
    // верх (GL, Y вверх).
    //
    // Двойной smoothstep даёт S с плоскими концами и крутой серединой:
    // волна долго идёт низко слева, резко набирает в центре и выполаживается
    // в гребень. Одного smoothstep не хватало — получалась ровная диагональ.
    // Синус сверху ломает математическую правильность: без него кривая
    // читается как график, а не как вода.
    '  float sx = smoothstep(-0.02, 0.92, uv.x);',
    '  sx = smoothstep(0.0, 1.0, sx);',

    // Подъём привязан к пропорциям канваса. Иначе на телефоне те же 0.45 по
    // высоте приходятся на вчетверо меньшую ширину — волна встаёт почти
    // вертикально и композиция ломается.
    '  float aspK = clamp(asp / 1.22, 0.52, 1.16);',

    // Небольшой спад после 82% ширины: без него подъём монотонный и гребень
    // не читается как гребень — нужен перевал, за которым вода уходит за край.
    '  float ridge = 0.29 + 0.42 * aspK * sx',
    '              + 0.034 * sin(uv.x * 4.3 + t * 0.16)',
    '              - 0.05 * smoothstep(0.82, 1.0, uv.x);',

    // Вторая волна — почти горизонтальная, у нижней кромки экрана.
    // Она только связывает композицию, поэтому и амплитуда, и вес малы.
    '  float ridge2 = 0.245 + 0.030 * sin(uv.x * 2.7 - 0.9 - t * 0.11);',

    // Полуширина полосы. Нужна и маске композиции, и валу в нормали, поэтому
    // считается здесь — до обоих. Сужена с прежних 0.20–0.46: на той ширине
    // вода занимала всю высоту правой половины и силуэта у неё не было.
    '  float sw = 0.18 + 0.24 * smoothstep(0.05, 0.72, uv.x);',

    // Тёмный канвас финальной секции делит этот же шейдер, но там вода
    // заливает кадр целиком — композиция и изгиб ему не нужны.
    '  float comp = 1.0 - uDark;',

    '  vec2 p = uv * vec2(asp, 1.0) * 2.2;',

    // Ключевой приём. Домен сдвигается по вертикали на величину осевой
    // линии — в этих координатах волна становится горизонтальной. Значит
    // и вытяжка лент, и снос идут ВДОЛЬ S-кривой, а не по прямой диагонали:
    // сама структура материала изгибается вместе с формой. Сдвиг зависит
    // только от x, то есть это чистый сдвиг — шум не растягивается.
    '  p.y -= (ridge - 0.5) * 2.2 * 0.90 * comp;',

    // Направление течения В ИЗОГНУТОМ домене: почти вдоль волны, с лёгким
    // подъёмом поперёк неё. На экране изгиб добавляет свой наклон, и
    // суммарно материал уходит вправо-вверх — тем же жестом, что и форма.
    '  vec2 dir = comp > 0.5 ? normalize(vec2(0.985, 0.17)) : normalize(vec2(-0.86, -0.51));',

    // Знак важен: поле сэмплируется как F(p + D), поэтому значение,
    // бывшее в точке x0, появляется там, где p + D = x0 — то есть узор
    // едет в направлении МИНУС D. Чтобы масса шла вдоль dir, смещение
    // вычитается.
    //
    // Скорость. Единица поля p равна H/2.2 экранных пикселей, снос идёт
    // со скоростью 0.15*K единиц в секунду — то есть ровно 80*K пикселей
    // в секунду на любом разрешении. K = 0.22 -> ~18 px/с: медленное
    // кинематографичное скольжение, крупная масса пересекает экран за минуту.
    // Тёмной секции оставлены её прежние 0.25.
    '  p -= dir * (t * mix(0.22, 0.25, uDark));',

    '  mat2 R = mat2(dir.x, dir.y, -dir.y, dir.x);',
    '  vec2 ps = R * p;',
    // сильная вытяжка вдоль потока: широкие ленты вместо пятен
    '  ps.x *= 0.30;',

    // Сдвиг домена — не косметика. Сжатие ps.x сажает выборку на узкую
    // полосу решётки шума, и при новом, почти горизонтальном dir она попала
    // на участок, где поле систематически ниже: средняя высота падала с 0.30
    // до 0.11 и вода почти исчезала. Сдвиг возвращает выборку на нормальный
    // участок. Правится домен, а не GAIN: GAIN задаёт крутизну нормалей,
    // то есть блики, и трогать его ради уровня плотности нельзя.
    '  ps.y -= 2.0 * comp;',

    /* ---------- курсор: мягкая линза ---------- */
    '  vec2 md = gl_FragCoord.xy - uMouse;',
    '  float r = length(md);',
    '  vec2 rdir = r > 0.0001 ? md / r : vec2(0.0);',
    '  float q = r / max(uRadius, 1.0);',

    // Один гладкий колокол вместо пары «плато + вал»: у него нет кромки,
    // поэтому эффект читается как локальное преломление, а не как диск.
    '  float lens = exp(-q * q * 1.35) * uMouseAmt;',

    // Смещение линзы: ноль в центре, максимум в средней зоне, плавно в ноль
    // на периферии. Ноль в центре и убирает стягивание в точку курсора.
    '  float disp = q * exp(-q * q * 1.1) * uMouseAmt;',
    '  ps -= R * rdir * disp * 0.30;',

    // Тёмной секции время варпа подаётся с прежним знаком: её внутреннее
    // движение должно остаться ровно таким, каким было.
    '  float tw = uDark > 0.5 ? -t : t;',
    '  vec2 wo = warpOffset(ps, tw);',
    '  float e = 0.006;',
    '  float h  = fbm4(ps + wo);',
    '  float hx = fbm4(ps + vec2(e, 0.0) + wo);',
    '  float hy = fbm4(ps + vec2(0.0, e) + wo);',

    // Вытяжка домена ради длинных лент срезает контраст поля. Возвращаем
    // усилением вокруг среднего — заодно круче нормали, то есть блики.
    '  const float GAIN = 2.55;',
    '  const float MID  = 0.47;',
    '  h  = (h  - MID) * GAIN + MID;',
    '  hx = (hx - MID) * GAIN + MID;',
    '  hy = (hy - MID) * GAIN + MID;',

    '  vec2 grad = vec2((h - hx) / e, (h - hy) / e);',

    // Вал волны. Поле шума однородно по кадру: любая его точка статистически
    // не отличается от любой другой, поэтому само по себе оно даёт ровную гофру
    // без главной формы — это и читается рулоном ткани. Реф держится на одном
    // крупном валу вдоль гребня: светлая верхняя кромка и тёмная изнанка.
    // Вал добавляется аналитически прямо в градиент высоты, второй раз поле
    // считать не нужно. Профиль асимметричный — сверху круче, снизу масса
    // свисает; те же пропорции, что у маски, чтобы форма и силуэт совпали.
    // Знак: grad хранит МИНУС производную (h - h(x+e)), отсюда плюс у rollG.
    '  float ru = (uv.y - ridge) / sw;',
    '  float rw = ru > 0.0 ? 0.62 : 1.35;',
    '  float rz = ru / rw;',
    '  float rollG = 2.6 * rz * exp(-rz * rz * 1.1) / (sw * rw * 2.2);',
    '  grad.y += rollG * 0.30 * comp;',

    '  vec3 n = normalize(vec3(grad, 2.15));',

    // Мелкая рябь подмешивается ТОЛЬКО в нормаль и не трогает плотность:
    // крупная форма остаётся цельной, но появляются стеклянные блики.
    // Без неё поверхность читается как атлас, а не как вода.
    // Три дешёвых noise вместо трёх fbm — рябь высокочастотная, октавы ей не нужны.
    '  vec2 fp = (ps + wo) * 1.7;',
    '  float fn  = noise(fp);',
    '  float fnx = noise(fp + vec2(0.045, 0.0));',
    '  float fny = noise(fp + vec2(0.0, 0.045));',
    '  n = normalize(vec3(n.xy + vec2(fn - fnx, fn - fny) * 1.4, n.z));',

    // Под курсором поверхность разглаживается лишь слегка: основную
    // работу делает смещение выборки выше, то есть преломление, а не
    // размытие — иначе эффект читается как blur-круг.
    '  n = normalize(mix(n, vec3(0.0, 0.0, 1.0), lens * 0.28));',
    '  h += lens * 0.038;',

    '  vec3 L = normalize(vec3(-0.48, 0.55, 0.68));',
    '  float diff = clamp(dot(n, L) * 0.5 + 0.5, 0.0, 1.0);',
    '  vec3 hv = normalize(L + vec3(0.0, 0.0, 1.0));',
    '  float sp = clamp(dot(n, hv), 0.0, 1.0);',
    '  float spec  = pow(sp, 30.0);',
    '  float spec2 = pow(sp, 110.0);',

    // Кромка стекла: там, где поверхность круто заворачивается, нормаль
    // ложится набок. Подсветка по этому признаку даёт объём и толщину.
    '  float edge = pow(1.0 - clamp(n.z, 0.0, 1.0), 2.6);',

    /* ---------- маска композиции ---------- */
    // Профиль поперёк осевой — супергаусс (степень 3, а не 2): внутри полосы
    // почти плато, спад по краю резкий. Обычный гаусс размазывал тело волны
    // и она читалась дымкой, а не материалом.
    //
    // Сверху спад втрое круче, чем снизу: у гребня появляется кромка, а масса
    // свисает вниз — как у настоящего вала воды. Толщина растёт к правой
    // трети, где волна набирает объём. Ширина sw посчитана выше, у композиции:
    // её же берёт вал в нормали, чтобы форма и силуэт не разъезжались.
    // Кромка волны не должна быть математической кривой. Подмешиваем в
    // поперечную координату низкочастотный шум по x — граница начинает гулять,
    // и силуэт перестаёт читаться маской под градиентом. Шум зависит от uv.x и
    // очень медленного времени, поэтому это плавное покачивание кромки, а не
    // дрожь по кадру.
    '  float wob = (noise(vec2(uv.x * 3.1, t * 0.05 + 4.0)) - 0.5) * 0.11 * comp;',
    '  float du = uv.y - ridge + wob;',
    '  float kk = du / (du > 0.0 ? sw * 0.48 : sw * 0.95);',
    '  float band = exp(-pow(abs(kk), 3.0));',

    // Зона заголовка гасится адресно — по x И по y. Гашение одним градиентом
    // по x убирало заодно и низкий вход волны слева, который по композиции
    // как раз нужен.
    '  float guard = 1.0 - 0.68 * smoothstep(0.68, 0.16, uv.x) * smoothstep(0.36, 0.70, uv.y);',
    // Воздух у самой верхней кромки: гребень остаётся высоким, но не
    // упирается в край — иначе масса читается как обрезанная.
    '  float airTop = 1.0 - 0.35 * smoothstep(0.78, 1.0, uv.y);',
    // База опущена с 0.46 до 0.30, а набор веса сдвинут вправо: центр Hero
    // отдаёт массу, гребень справа её сохраняет. Композиция та же, воздуха больше.
    //
    // Нижний правый угол снимает ещё 30%: там подол волны накладывался сам на
    // себя и зона под карточкой была вдвое толще остальных (0.64 против 0.30).
    '  float lowRight = 1.0 - 0.32 * smoothstep(0.46, 0.95, uv.x) * smoothstep(0.64, 0.24, uv.y);',
    // База поднята с 0.30 до 0.55: левый вход волны в рефе читается, а не
    // угадывается, и чистой бумаги в зоне воды там практически нет — на 30%
    // голого листа, которые оставалась у нас, у рефа приходится 1.7%.
    // Верх слева по-прежнему держит guard, там лист остаётся под заголовок.
    '  float amp = (0.55 + 0.45 * smoothstep(0.10, 0.72, uv.x)) * guard * airTop * lowRight;',

    // Верхняя вуаль. В рефе вода идёт и поверх заголовка — совсем тонкой
    // плёнкой, от которой лист просто перестаёт быть пустым. Осевая линия
    // основной волны на левой трети лежит низко, у нижней кромки, поэтому
    // зона заголовка оставалась сухой при любом guard: туда не дотягивается
    // сама полоса, а не гасит её защита. Отсюда отдельная почти горизонтальная
    // полоса у верхней кромки с малым весом — присутствие есть, читаемость
    // текста не трогается.
    '  float ridge3 = 0.76 + 0.045 * sin(uv.x * 3.1 + 1.7 + t * 0.09);',
    '  float dv3 = (uv.y - ridge3) / 0.13;',
    '  float band3 = exp(-dv3 * dv3) * 0.22 * (0.40 + 0.60 * smoothstep(0.0, 0.5, uv.x));',

    '  float dv = (uv.y - ridge2) / 0.15;',
    // Вес поднят с 0.14–0.27 до 0.30–0.50: на прежнем нижняя волна тонула и
    // низ первого экрана оставался сухим листом, тогда как в рефе вода широко
    // стелется под текстом во всю ширину и уходит за левый край.
    '  float band2 = exp(-dv * dv) * (0.30 + 0.20 * smoothstep(0.10, 0.80, uv.x));',

    '  float shape = clamp(band * amp + band2 + band3 * comp, 0.0, 1.0);',
    // Обострение краёв маски: без него дальний хвост полосы держал заметный
    // вес у верхней кромки и масса выползала за композицию.
    '  shape = smoothstep(0.10, 0.82, shape);',
    '  shape = mix(1.0, shape, comp);',

    // Плотность — аддитивная смесь маски и поля высот, а не порог по одному
    // полю. Причина: уровень fbm сам по себе медленно плавает, пока снос
    // тащит выборку по неоднородному полю. При чистом пороге это гуляние
    // било прямо по силуэту — волна то раздувалась за свои границы, то почти
    // исчезала. Здесь вклад h ослаблен до 0.62, форму держит маска, и разброс
    // средней плотности по времени падает с 0.23 до 0.04. Поле по-прежнему
    // рвёт край органически, но больше не управляет композицией.
    // В тёмной секции всё как было: там маски нет и работает чистое h.
    '  float lvl = 0.47 + (h - 0.47) * 0.62 + (shape - 0.45) * 1.00;',
    '  float dLo = mix(0.24, 0.28, uDark);',
    '  float dHi = mix(1.12, 0.70, uDark);',
    '  float dens = clamp(smoothstep(dLo, dHi, mix(lvl, h, uDark)), 0.0, 1.0);',

    /* ---------- толща материала ---------- */
    // Цвет больше не выбирается лестницей mix по плотности — он считается
    // как поглощение света в толще (Бугер-Ламберт). Из-за экспоненты глубина
    // набирается нелинейно: тонкие места остаются почти бесцветными, средние
    // уходят в бирюзу, а самые толстые — в глубокий teal. Лестница mix давала
    // равномерно подкрашенную заливку, отчего вода читалась гелем.
    //
    // Толща собирается из локальных признаков, а НЕ из абсолютной высоты
    // поля: h медленно плавает вместе со сносом, и привязка к нему вернула бы
    // дыхание уровня, от которого силуэт уже избавлен.
    '  float under = clamp(-n.y, 0.0, 1.0);',

    // Плотность выше dHi срезается клампом, но именно это переполнение и
    // означает наложение слоёв — в толще оно должно учитываться.
    '  float over = max(mix(lvl, h, uDark) - dHi, 0.0);',

    // Склон поверхности — главный признак материала. На плоском участке он
    // нулевой, на завороте складки растёт. Нормировка slope/(1+slope) держит
    // его в 0..1 и не даёт самым крутым местам уехать в бесконечность.
    '  float slope = length(n.xy);',
    '  float fold  = slope / (1.0 + slope);',

    // Сторона складки относительно света. Теневая сторона набирает толщу,
    // освещённая остаётся тонкой и отдаёт узкий блик — именно из этой пары
    // складка и читается объёмной, а не крашеной полосой.
    '  vec2  fdir  = slope > 1e-4 ? n.xy / slope : vec2(0.0);',
    '  float side  = dot(fdir, L.xy);',
    '  float shade = clamp(0.5 - 0.5 * side, 0.0, 1.0);',

    // Каустика — отдельным слоем, а не из поля формы. Причина: fbm4 обрывается
    // на октаве с ячейкой около 50 px, это и есть та ровная гофра, которую глаз
    // читает тканью. Тонких нитей в нём нет ни на какой настройке — пробовал
    // снимать их лапласианом того же поля, поле оказалось для этого слишком
    // гладким (разброс ±0.03 при нужных ±1).
    //
    // Ридж 1 - |2n - 1| даёт не пятна, а линии: у него излом ровно там, где шум
    // проходит середину. Домен вытянут ещё вдесятеро вдоль потока — нити идут
    // ВДОЛЬ течения, как в воде, а не поперёк. Две октавы: 20 px и 11 px.
    '  vec2 cq = (ps + wo * 0.35) * vec2(3.0, 20.0);',
    '  float c1 = 1.0 - abs(2.0 * noise(cq) - 1.0);',
    '  float c2 = 1.0 - abs(2.0 * noise(cq * 1.6 + 5.1) - 1.0);',
    // Показатель второй октавы снижен с 7 до 4.5: на семёрке нить рвалась в
    // пунктир и читалась строчкой точек, а не линией.
    '  float caus = pow(c1, 4.0) * 0.62 + pow(c2, 4.5) * 0.38;',

    // Нити не должны лежать ровным ковром: в воде они собираются там, где
    // поверхность уже изогнута. Низкочастотная маска добавляет к этому
    // неравномерность по кадру.
    '  float causM = smoothstep(0.30, 0.80, noise(ps * vec2(0.9, 1.6) + 17.0));',
    '  caus *= dens * (0.30 + 0.70 * smoothstep(0.02, 0.26, fold)) * (0.35 + 0.65 * causM);',

    // Ленты. Главное отличие от рефа было не в цвете и не в частоте деталей —
    // эти метрики сходились, — а в ОДНОРОДНОСТИ: у поля шума всюду одинаковая
    // амплитуда, поэтому масса ложилась ровной гофрой во всю правую половину.
    // В рефе вода идёт длинными лентами разной плотности.
    //
    // Маска работает по толще, а не по силуэту: пробовал умножать на неё саму
    // композицию — вода просто исчезала, потому что нелинейное окно shape
    // съедало всё, что оказалось ниже единицы. Да и по существу правильнее так:
    // между лентами в рефе не голая бумага, а очень тонкая вода.
    //
    // Порог стоит по ФАКТИЧЕСКОМУ среднему поля, а не по 0.5. Домен здесь сжат
    // по x дважды (ps.x *= 0.30, потом ещё 0.30), выборка идёт узкой полосой
    // решётки шума и её среднее уезжает — замеряно 0.39.
    '  vec2 rq = ps * vec2(0.30, 0.62) + vec2(3.7, 1.1);',
    '  float rb = noise(rq) * 0.66 + noise(rq * 2.1 + 8.3) * 0.34;',
    // Диапазон 0.55–1.45, среднее около единицы. На более контрастном 0.30–1.75
    // разброс насыщенности разъезжался: медиана вставала на реф, а p90 уходила
    // на 0.50 против 0.346 — плотные ленты перетяжелялись.
    '  float ribbon = mix(1.0, 0.55 + 0.90 * smoothstep(0.28, 0.50, rb), comp);',

    // Толща целиком построена на СКЛОНЕ, а не на плотности. Раньше база была
    // dens*(0.02+0.20*dens) — около 0.15 толщи на ВСЕЙ площади волны, и
    // экспонента поглощения красила всё подряд ровным средним бирюзовым.
    // У шёлка контраст равномерный, у стекла он весь в кромках — отсюда и
    // читался атлас. Сейчас база в двадцать раз меньше (плоское место сходится
    // к цвету бумаги и становится невидимым), а цвет приносит складка.
    //
    // Показатель 2.10 подобран по рефу: там медиана насыщенности 0.167 при
    // нижнем проценте яркости 0.41, то есть основная масса воды почти
    // бесцветная, а цвет сидит в считанных процентах площади. На пологом 1.55
    // при том же тёмном хвосте медиана насыщенности выходила 0.25 и вода была
    // ровно бирюзовой: степень убирает толщу из средних складок, не трогая
    // глубокие.
    '  float thick = dens * (0.006 + 0.030 * dens) + over * 0.22;',
    '  thick += dens * 3.00 * pow(fold, 2.10) * (0.30 + 0.85 * shade);',
    '  thick *= 1.0 + 0.55 * under;',
    '  thick *= ribbon;',
    // Там, где лучи сошлись, лист под плёнкой светлеет, а материал читается
    // тоньше; между нитями остаётся своя толща.
    '  thick *= 1.0 - 0.62 * caus;',

    // Гамма. Показатель мягкий: на прежних 1.95 всё тонкое прибивалось в ноль,
    // и после переезда толщи на склон вода стала бесцветной плёнкой — медиана
    // насыщенности падала до 0.04 против 0.167 у рефа, половина площади
    // оставалась чистой бумагой. Множитель ставит медиану толщи примерно на
    // 0.11: при такой толще и этом ABSORB получается ровно тот мягкий флёр,
    // которым в рефе залита вся площадь воды.
    '  thick = pow(thick, 1.35) * 3.90;',
    // Мягкое насыщение — не косметика, а форма распределения. Потолок низкий
    // намеренно: без него верхний хвост толщи выходил вдвое тяжелее рефовского,
    // и при медиане насыщенности точно на рефе p90 уезжала на 0.50 против
    // 0.346, а нижний процент яркости проваливался до 0.32 против 0.41.
    // Функция поджимает именно хвост и оставляет середину как есть.
    '  thick = thick / (1.0 + thick / 1.10);',

    // Красный гасится вдвое с лишним быстрее зелёного — так вода и становится
    // бирюзовой. Синий гаснет чуть МЕДЛЕННЕЕ зелёного: тонкий материал уходит
    // в холодный циан около 186°, а глубокие места ведёт SCATTER, он зеленее.
    // Вместе это даёт разброс оттенка, который есть в рефе; прежняя пара
    // 0.62/0.66 держала всю воду на плоских 175–178°, и это добавляло ощущение
    // крашеной плёнки.
    //
    // Абсолютный уровень всех трёх каналов важен отдельно от их разности.
    // Разность задаёт цветность на единицу толщи, а общий уровень — насколько
    // при этой цветности падает яркость. Поднятый уровень делает воду чуть
    // сероватой, как в рефе, вместо чистого циана.
    '  vec3 ABSORB = vec3(2.650, 1.190, 1.000);',

    // Дисперсия: на изгибах каналы расходятся по длине пути, как в стекле.
    // Эффект едва заметен, но именно он читается как преломление.
    '  vec3 DISP = vec3(1.0 + 0.10 * edge, 1.0, 1.0 - 0.08 * edge);',

    // Многократное рассеяние в толще. Без него полностью поглощённые места
    // уходят в бесцветный тёмно-серый и выглядят грязью; с ним самая глубокая
    // складка садится в насыщенный emerald.
    '  vec3 SCATTER = vec3(0.018, 0.152, 0.106);',

    // ВАЖНО: подложка — цвет бумаги страницы (--paper в style.css), а не
    // белый. Прозрачное стекло не может быть ЯРЧЕ фона, за которым лежит;
    // с белой подложкой тонкая плёнка подсвечивала страницу, и 93% всех
    // засветов приходилось именно на неё, а вовсе не на блики. Теперь тонкий
    // материал сходится к фону, то есть становится невидимым, а не светящимся.
    // Если поменяется --paper, это значение надо обновить следом.
    '  vec3 PAPER = vec3(0.957, 0.973, 0.965);',

    // Внутреннее затенение работает только там, где есть чему затеняться:
    // на тонких участках свет проходит насквозь и гасить его нечем.
    '  float lit = mix(1.0, 0.50 + 0.52 * diff, smoothstep(0.004, 0.09, thick));',

    // Блик. Прежний был прижат потолком 0.30 и размазан по всей поверхности —
    // отсюда матовость. Теперь он сажается на ОСВЕЩЁННУЮ сторону складки
    // (crest) и там ему разрешено дойти почти до белого: в рефе свет живёт
    // бритвенными линиями по гребням, а не общей подсветкой.
    '  float crest = pow(fold, 1.30) * clamp(0.5 + 0.5 * side, 0.0, 1.0);',
    '  float hi = (spec * 0.05 + spec2 * spec * 0.50) * (0.30 + 1.40 * crest);',
    '  hi += crest * crest * 0.26;',
    // Гашение теперь по складке, а не по толще: на плоской плёнке блика быть
    // не должно вовсе, иначе он снова подсветит страницу.
    '  hi *= dens * (0.12 + 0.88 * smoothstep(0.04, 0.35, fold));',
    // Светлая нить каустики идёт мимо гейта по складке: она живёт как раз там,
    // где поверхность почти плоская, но лучи уже сошлись.
    '  hi += caus * 0.26;',
    // Кромка листа. У стекла на срезе полное внутреннее отражение, поэтому
    // край плёнки — тонкая светлая линия. Без неё силуэт воды остаётся мягкой
    // растушёвкой и крупная форма в кадре не читается вовсе.
    '  float sEdge = smoothstep(0.05, 0.24, shape) * (1.0 - smoothstep(0.24, 0.56, shape));',
    '  hi += sEdge * 0.20 * comp;',
    '  hi = min(hi, 0.75);',

    '  vec3 tr = exp(-ABSORB * thick * DISP);',
    '  vec3 lc = PAPER * tr * lit + SCATTER * (1.0 - tr) + hi;',

    // Пузыри — только в светлой ветке и только внутри тела волны. Всплывают
    // медленнее, чем идёт снос: масса течёт вправо, пузырь уходит вверх.
    // Кольцо делится на тёмную и светлую половину по направлению света —
    // без этого пузырь читается плоским значком, а не сферой в толще.
    '  if (comp > 0.5) {',
    '    vec2 bq = uv * vec2(asp, 1.0) * 4.6 + vec2(-t * 0.085, t * 0.045);',
    '    vec3 b1 = bubble(bq, 3.1);',
    '    vec3 b2 = bubble(bq * 2.35 + 4.4, 11.7);',
    // Низкочастотная маска собирает пузыри в пару облаков. Равномерная россыпь
    // по всей волне — это текстура, а в воде пузыри всегда кучкуются.
    '    float cloud = smoothstep(0.30, 0.66, noise(uv * vec2(asp, 1.0) * 1.9 + vec2(11.0, 3.0) - t * 0.04));',
    '    float bm = dens * shape * (0.35 + 0.65 * cloud);',
    '    float body = (b1.x * 0.55 + b2.x * 0.32) * bm;',
    '    float rimD = (b1.y * max(-b1.z, 0.0) + b2.y * 0.62 * max(-b2.z, 0.0)) * bm;',
    '    float rimL = (b1.y * max( b1.z, 0.0) + b2.y * 0.62 * max( b2.z, 0.0)) * bm;',
    '    lc *= 1.0 - body * vec3(0.22, 0.075, 0.062);',
    '    lc *= 1.0 - rimD * 0.55;',
    '    lc += rimL * 0.34;',
    '  }',

    '  vec3 d1 = vec3(0.031, 0.122, 0.098);',
    '  vec3 d2 = vec3(0.051, 0.212, 0.173);',
    '  vec3 d3 = vec3(0.090, 0.373, 0.306);',
    '  vec3 d4 = vec3(0.325, 0.663, 0.573);',
    '  vec3 dc = mix(d1, d2, smoothstep(0.02, 0.38, dens));',
    '  dc = mix(dc, d3, smoothstep(0.34, 0.74, dens));',
    '  dc = mix(dc, d4, smoothstep(0.68, 1.00, dens) * 0.68);',
    '  dc *= 0.80 + 0.36 * diff;',
    '  dc += spec * 0.20 + spec2 * 0.34 + edge * 0.08;',

    '  vec3 col = mix(lc, dc, uDark);',

    // Прозрачность ведёт композиция, а не градиент по углу экрана: тело
    // волны плотное, вокруг него лёгкая дымка, слева за заголовком почти
    // чистый лист. Гасим прозрачностью, а не подмесом белого, иначе
    // страница сереет.
    '  float fade = smoothstep(0.0, 0.10, uv.y);',
    // Силуэт ведёт не одна маска, а маска ВМЕСТЕ с плотностью. Пока альфа
    // зависела только от shape, край воды был гладкой математической кривой —
    // отсюда ощущение заливки под градиентом. Множитель по dens рвёт кромку
    // полем высот, как рвётся край реальной плёнки. Композицию по-прежнему
    // держит shape, поэтому «дыхание» уровня h сюда не возвращается: вклад h
    // в lvl ослаблен до 0.62 и силуэт от него не зависит.
    '  float alpha = mix(pow(clamp(shape, 0.0, 1.0), 1.05)',
    '                    * smoothstep(0.0, 0.12, dens) * fade, 1.0, uDark);',

    // Дизеринг: на пологих светлых градиентах 8 бит дают видимые ступени.
    '  float dth = (hash(gl_FragCoord.xy + fract(uTime)) - 0.5) / 255.0;',
    '  col += dth;',

    '  gl_FragColor = vec4(col, alpha);',
    '}'
  ].join('\n');

  Array.prototype.forEach.call(canvases, init);

  function init(canvas) {
    var gl = canvas.getContext('webgl', { alpha: true, antialias: false, premultipliedAlpha: false })
          || canvas.getContext('experimental-webgl', { alpha: true, antialias: false });

    if (!gl) { document.documentElement.classList.add('no-webgl'); return; }

    var dark = canvas.dataset.tone === 'dark' ? 1.0 : 0.0;

    function compile(type, src) {
      var sh = gl.createShader(type);
      gl.shaderSource(sh, src);
      gl.compileShader(sh);
      if (!gl.getShaderParameter(sh, gl.COMPILE_STATUS)) {
        console.warn('water shader:', gl.getShaderInfoLog(sh));
        return null;
      }
      return sh;
    }

    var vs = compile(gl.VERTEX_SHADER, VERT);
    var fs = compile(gl.FRAGMENT_SHADER, FRAG);
    if (!vs || !fs) { document.documentElement.classList.add('no-webgl'); return; }

    var prog = gl.createProgram();
    gl.attachShader(prog, vs);
    gl.attachShader(prog, fs);
    gl.linkProgram(prog);
    if (!gl.getProgramParameter(prog, gl.LINK_STATUS)) {
      document.documentElement.classList.add('no-webgl');
      return;
    }
    gl.useProgram(prog);

    var buf = gl.createBuffer();
    gl.bindBuffer(gl.ARRAY_BUFFER, buf);
    gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1, -1, 3, -1, -1, 3]), gl.STATIC_DRAW);
    var aPos = gl.getAttribLocation(prog, 'aPos');
    gl.enableVertexAttribArray(aPos);
    gl.vertexAttribPointer(aPos, 2, gl.FLOAT, false, 0, 0);

    var uRes = gl.getUniformLocation(prog, 'uRes');
    var uTime = gl.getUniformLocation(prog, 'uTime');
    var uMouse = gl.getUniformLocation(prog, 'uMouse');
    var uMouseAmt = gl.getUniformLocation(prog, 'uMouseAmt');
    var uRadius = gl.getUniformLocation(prog, 'uRadius');
    gl.uniform1f(gl.getUniformLocation(prog, 'uDark'), dark);

    gl.enable(gl.BLEND);
    gl.blendFunc(gl.SRC_ALPHA, gl.ONE_MINUS_SRC_ALPHA);

    // Разрешение: целимся в физические пиксели экрана, но при просадке
    // FPS опускаемся по ступеням. Красиво по умолчанию, плавно на слабом.
    var dpr = Math.min(window.devicePixelRatio || 1, 2);
    var STEPS = [1.0, 0.8, 0.62, 0.48, 0.36];
    // На телефоне стартуем со сниженной ступени: там DPR 3, слабая GPU,
    // и первые секунды на полном разрешении заметно тормозят. Если
    // железо тянет, цикл сам поднимет качество обратно через ~4 секунды.
    var lean = window.innerWidth < 820 || (navigator.hardwareConcurrency || 8) <= 4;
    var step = lean ? 2 : 0;
    var scale = dpr * STEPS[step];

    function resize() {
      var w = Math.max(1, Math.round(canvas.clientWidth * scale));
      var h = Math.max(1, Math.round(canvas.clientHeight * scale));
      if (canvas.width === w && canvas.height === h) return;
      canvas.width = w;
      canvas.height = h;
      gl.viewport(0, 0, w, h);
      gl.uniform2f(uRes, w, h);
      gl.uniform1f(uRadius, RADIUS_CSS_PX * scale);
    }

    var reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    var visible = true;
    var raf = null;
    var start = performance.now() - (dark ? 41000 : 0);

    /* ---------- курсор ---------- */
    // Цель и текущее положение разведены: курсор прыгает по пикселям,
    // а вода должна догонять его плавно, иначе бугор дёргается.
    var tgX = -9999, tgY = -9999, curX = -9999, curY = -9999;
    var tgAmt = 0, curAmt = 0;
    var pointerFine = window.matchMedia('(pointer: fine)').matches;

    function onMove(ev) {
      var r = canvas.getBoundingClientRect();
      if (!r.width || !r.height) return;
      var x = ev.clientX - r.left;
      var y = ev.clientY - r.top;
      var inside = x >= -60 && y >= -60 && x <= r.width + 60 && y <= r.height + 60;
      tgAmt = inside ? 1 : 0;
      if (!inside) return;
      // в пиксели рендера, с переворотом Y: у WebGL начало снизу
      tgX = x * (canvas.width / r.width);
      tgY = (r.height - y) * (canvas.height / r.height);
      if (curX < -9000) { curX = tgX; curY = tgY; }
    }

    if (pointerFine && !reduced) {
      window.addEventListener('mousemove', onMove, { passive: true });
      window.addEventListener('mouseout', function (e) { if (!e.relatedTarget) tgAmt = 0; }, { passive: true });
    }

    /* ---------- цикл ---------- */
    var slow = 0, fast = 0, prev = 0;

    function frame(now) {
      resize();

      // догон курсора и плавное угасание влияния
      curX += (tgX - curX) * 0.085;
      curY += (tgY - curY) * 0.085;
      curAmt += (tgAmt - curAmt) * 0.05;
      gl.uniform2f(uMouse, curX, curY);
      gl.uniform1f(uMouseAmt, curAmt);

      gl.uniform1f(uTime, (now - start) / 1000);
      gl.drawArrays(gl.TRIANGLES, 0, 3);

      // Ступенчатая деградация: 12 тяжёлых кадров подряд — снижаем
      // разрешение; 240 лёгких — пробуем вернуть обратно.
      if (prev) {
        var dt = now - prev;
        if (dt > 26) { slow++; fast = 0; } else if (dt < 19) { fast++; slow = 0; }
        if (slow > 12 && step < STEPS.length - 1) {
          step++; scale = dpr * STEPS[step]; slow = 0;
          canvas.width = 0; resize();
        } else if (fast > 240 && step > 0) {
          step--; scale = dpr * STEPS[step]; fast = 0;
          canvas.width = 0; resize();
        }
      }
      prev = now;

      raf = visible ? requestAnimationFrame(frame) : null;
    }

    function play() { if (raf === null && visible) { prev = 0; raf = requestAnimationFrame(frame); } }
    function stop() { if (raf !== null) { cancelAnimationFrame(raf); raf = null; } }

    if (reduced) {
      resize();
      gl.uniform2f(uMouse, -9999, -9999);
      gl.uniform1f(uMouseAmt, 0);
      gl.uniform1f(uTime, 12.0);
      gl.drawArrays(gl.TRIANGLES, 0, 3);
    } else {
      if ('IntersectionObserver' in window) {
        new IntersectionObserver(function (entries) {
          visible = entries[0].isIntersecting;
          if (visible) play(); else stop();
        }, { rootMargin: '120px' }).observe(canvas);
      }
      document.addEventListener('visibilitychange', function () {
        if (document.hidden) stop(); else play();
      });
      window.addEventListener('resize', resize, { passive: true });
      play();
    }

    canvas.addEventListener('webglcontextlost', function (e) {
      e.preventDefault();
      stop();
      document.documentElement.classList.add('no-webgl');
    });
  }
})();
